const SKIP_TAGS = new Set(['SCRIPT','STYLE','SVG','PATH','NOSCRIPT','VIDEO','IMG','INPUT','TEXTAREA','CODE','PRE']);

function normKey(s){
  return String(s || '').replace(/\s+/g, ' ').trim();
}

function t(key){
  const lang = window.__lang || 'en';
  if (lang === 'en' || !I18N[lang]) return key;
  const hit = I18N[lang][normKey(key)];
  return hit !== undefined ? hit : key;
}

function translateAttrs(root, lang){
  const dict = I18N[lang] || null;
  root.querySelectorAll('[aria-label], [title], [placeholder], [alt]').forEach(el => {
    ['aria-label', 'title', 'placeholder', 'alt'].forEach(attr => {
      if (!el.hasAttribute(attr)) return;
      const cacheKey = '__i18n_' + attr;
      if (el[cacheKey] === undefined) el[cacheKey] = el.getAttribute(attr);
      const src = el[cacheKey];
      if (!src) return;
      if (!dict) { el.setAttribute(attr, src); return; }
      const hit = dict[normKey(src)];
      el.setAttribute(attr, hit !== undefined ? hit : src);
    });
  });
}

function translateHtmlBlocks(root, lang){
  root.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (!key) return;
    if (el.__i18nHtmlSource === undefined) el.__i18nHtmlSource = el.innerHTML;
    const pack = I18N_HTML[key];
    if (!pack){ el.innerHTML = el.__i18nHtmlSource; return; }
    el.innerHTML = pack[lang] || pack.en || el.__i18nHtmlSource;
  });
}

function translateNode(root, lang){
  if (!root) return;
  const dict = I18N[lang] || null;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(n){
      if (!n.nodeValue || !n.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      let p = n.parentElement;
      while (p){
        if (SKIP_TAGS.has(p.tagName)) return NodeFilter.FILTER_REJECT;
        if (p.hasAttribute && p.hasAttribute('data-no-i18n')) return NodeFilter.FILTER_REJECT;
        if (p.hasAttribute && p.hasAttribute('data-i18n-html')) return NodeFilter.FILTER_REJECT;
        p = p.parentElement;
      }
      return NodeFilter.FILTER_ACCEPT;
    }
  });
  const nodes = [];
  let n; while ((n = walker.nextNode())) nodes.push(n);

  nodes.forEach(node => {
    if (node.__i18nSource === undefined) node.__i18nSource = node.nodeValue;
    const src = node.__i18nSource;
    const lead = (src.match(/^\s*/) || [''])[0];
    const trail = (src.match(/\s*$/) || [''])[0];
    const key = normKey(src);
    if (!dict){ node.nodeValue = src; return; }
    const hit = dict[key];
    node.nodeValue = hit !== undefined ? (lead + hit + trail) : src;
  });

  translateAttrs(root, lang);
  translateHtmlBlocks(root, lang);
}

function setLang(lang, opts = {}){
  window.__lang = lang;
  translateNode(document.body, lang);
  document.documentElement.lang = lang;
  try { localStorage.setItem('victory-lang', lang); } catch(e){}
  document.querySelectorAll('.lang-opt').forEach(b => b.classList.toggle('active', b.dataset.lang === lang));
  const cur = document.querySelector('.lang-current');
  if (cur) cur.textContent = (LANGS.find(l => l.code === lang) || LANGS[0]).label;
  if (!opts.silent) document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
}

function getLang(){
  try { return localStorage.getItem('victory-lang') || 'en'; } catch(e){ return 'en'; }
}

function buildLangSwitcher(){
  const mount = document.getElementById('langSwitch');
  if (!mount) return;
  mount.innerHTML = `
    <button class="lang-toggle" aria-label="Language" aria-haspopup="true">
      <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.4" width="15" height="15"><circle cx="12" cy="12" r="9"/><path d="M3 12h18M12 3c2.5 2.7 3.8 5.7 3.8 9S14.5 18.3 12 21c-2.5-2.7-3.8-5.7-3.8-9S9.5 5.7 12 3z"/></svg>
      <span class="lang-current">EN</span>
    </button>
    <div class="lang-menu">
      ${LANGS.map(l => `<button class="lang-opt" data-lang="${l.code}"><b>${l.label}</b><span>${l.name}</span></button>`).join('')}
    </div>`;

  mount.querySelector('.lang-toggle').addEventListener('click', e => {
    e.stopPropagation();
    mount.classList.toggle('open');
  });
  mount.querySelectorAll('.lang-opt').forEach(b => {
    b.addEventListener('click', () => { setLang(b.dataset.lang); mount.classList.remove('open'); });
  });
  document.addEventListener('click', () => mount.classList.remove('open'));
}

document.addEventListener('DOMContentLoaded', () => {
  buildLangSwitcher();
  setLang(getLang(), { silent: true });
});

